/**
 * Compares the trigger-condition grammar (compiler/triggers.ts) with the Phase 1 adapter.
 *
 * Usage:
 *   node scripts/magic-triggers-diff.ts <oracle-cards.jsonl.gz> [--out <report.md>]
 *
 * Every triggered ability ("When/Whenever/At ...") in the precon cards and the bulk file has its
 * trigger head and intervening-if condition parsed both ways and bucketed (see magic-diff.ts). Only
 * the trigger and condition are compared, not the effect.
 */
import { writeFileSync } from 'node:fs';

import { adaptCard, type AdapterLog } from '../src/lib/magic/compiler/adapter.ts';
import { normalizeFace } from '../src/lib/magic/compiler/normalize.ts';
import { parseTriggerHeader } from '../src/lib/magic/compiler/triggers.ts';
import { normalizeScryfallCard } from '../src/lib/magic/scryfall.ts';
import type { ScryfallCard } from '../src/lib/magic/types.ts';
import { canonical, classify, renderReport, summaryRow, type DiffRow, type Side } from './magic-diff.ts';
import { buildTemplater, NON_GAME_LAYOUTS, preconCards, readBulk } from './magic-shared.ts';

const same = (a: unknown, b: unknown) => canonical(a) === canonical(b);

function triggerRows(card: ScryfallCard): DiffRow[] {
	if (card.backFace || card.oracleText.includes('\n//\n')) return [];
	const log: AdapterLog = { costs: [], triggers: [] };
	adaptCard(card, log);
	const norm = normalizeFace(card.name, card.oracleText);
	const rows: DiffRow[] = [];

	for (const line of norm.lines) {
		const parsed = parseTriggerHeader(line.body);
		if (!parsed) continue;
		const head = line.body.slice(0, parsed.effectStart).replace(/,\s*$/, '');
		const grammar: Side = {
			complete: parsed.unparsed.length === 0 && Boolean(parsed.trigger),
			value: { trigger: parsed.trigger, condition: parsed.condition }
		};
		const claim = log.triggers.find((t) => t.rawIndex === line.rawIndex);
		const adapter: Side | undefined = claim && {
			complete: claim.complete,
			value: { trigger: claim.trigger, condition: claim.condition }
		};
		rows.push({
			card: card.name,
			kind: 'trigger',
			text: head,
			bucket: classify(grammar, adapter, same),
			grammar,
			adapter,
			fragments: parsed.unparsed.map((s) => line.body.slice(s.start, s.end))
		});
	}
	return rows;
}

async function main(): Promise<void> {
	const argv = process.argv.slice(2);
	const bulkPath = argv.find((a) => !a.startsWith('--'));
	const outIdx = argv.indexOf('--out');
	const out = outIdx >= 0 ? argv[outIdx + 1] : undefined;
	if (!bulkPath) throw new Error('Usage: node scripts/magic-triggers-diff.ts <oracle-cards.jsonl.gz> [--out <file>]');

	const precon = preconCards().flatMap(triggerRows);
	const bulk: DiffRow[] = [];
	const subtypes = new Set<string>();
	for await (const raw of readBulk(bulkPath)) {
		if (NON_GAME_LAYOUTS.has(String(raw.layout ?? 'normal'))) continue;
		for (const tl of String(raw.type_line ?? '').split(' // ')) {
			const right = tl.split(' — ')[1];
			if (right) for (const s of right.split(/\s+/)) if (s) subtypes.add(s);
		}
		bulk.push(...triggerRows(normalizeScryfallCard(raw)));
	}

	const report = renderReport({
		title: 'Trigger grammar vs adapter',
		intro: [
			'Generated by `scripts/magic-triggers-diff.ts`. The head of each triggered ability ("When ~ enters",',
			'"At the beginning of your upkeep") and its intervening-if condition are parsed by the trigger',
			'grammar (`compiler/triggers.ts`) and by the Phase 1 adapter. Effects are not compared. The',
			'adapter counts as complete only when the runtime would honour the trigger as written (for',
			'example, it drops intervening-if conditions on enters/dies/attacks triggers).'
		],
		adapterNote: [
			'Either a gap in the grammar or the adapter (that is, the legacy rule tree and',
			'`parseStructuredTriggeredAbilities`, which the engine uses) claiming more than it understood.'
		],
		precon,
		bulk,
		templater: buildTemplater(subtypes)
	});

	if (out) writeFileSync(out, report);
	else process.stdout.write(report);
	console.error(`${summaryRow('precon', precon)}\n${summaryRow('bulk', bulk)}`);
}

await main();
