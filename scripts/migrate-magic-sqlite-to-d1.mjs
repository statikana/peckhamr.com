#!/usr/bin/env node
/**
 * Step 5.4: Export the Magic tables from a magic-backend SQLite file into a D1-compatible SQL file
 * (`CREATE TABLE IF NOT EXISTS` + `DELETE FROM` + size-batched `INSERT INTO`) suitable for:
 *   npx wrangler d1 execute cosmo_users --remote --file=magic-to-d1.sql
 *
 * Only touches the 6 Magic tables; other tables in `cosmo_users` (Cosmo, Notes, etc.) are untouched.
 *
 * Usage:
 *   node scripts/migrate-magic-sqlite-to-d1.mjs <input.sqlite> <output.sql> [--max-bytes=64000]
 */

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import { MAGIC_TABLES } from './migrate-magic-d1-to-sqlite.mjs';

export const DEFAULT_MAX_STATEMENT_BYTES = 64_000; // Safely below Cloudflare D1's 100 KB statement limit
export const DEFAULT_MAX_ROWS_PER_INSERT = 50;

const CREATE_SCHEMA_STATEMENTS = [
	`CREATE TABLE IF NOT EXISTS "MagicUsers" (
	id TEXT PRIMARY KEY,
	provider TEXT NOT NULL,
	provider_id TEXT NOT NULL,
	email TEXT DEFAULT '',
	username TEXT NOT NULL,
	avatar_url TEXT DEFAULT '',
	stats_json TEXT DEFAULT '{}',
	created_at INTEGER NOT NULL,
	last_login_at INTEGER NOT NULL
);`,
	`CREATE TABLE IF NOT EXISTS "MagicSessions" (
	token TEXT PRIMARY KEY,
	user_id TEXT NOT NULL,
	expires_at INTEGER NOT NULL,
	created_at INTEGER NOT NULL
);`,
	`CREATE TABLE IF NOT EXISTS "MagicDecks" (
	id TEXT PRIMARY KEY,
	user_id TEXT NOT NULL,
	name TEXT NOT NULL,
	description TEXT DEFAULT '',
	commanders_json TEXT NOT NULL,
	cards_json TEXT NOT NULL,
	color_identity TEXT NOT NULL,
	card_count INTEGER DEFAULT 100,
	is_legal INTEGER DEFAULT 1,
	validation_errors_json TEXT DEFAULT '[]',
	win_count INTEGER DEFAULT 0,
	play_count INTEGER DEFAULT 0,
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL
);`,
	`CREATE TABLE IF NOT EXISTS "MagicLobbies" (
	code TEXT PRIMARY KEY,
	name TEXT NOT NULL,
	host_user_id TEXT NOT NULL,
	status TEXT NOT NULL DEFAULT 'waiting',
	is_private INTEGER DEFAULT 1,
	rules_json TEXT NOT NULL,
	seats_json TEXT NOT NULL,
	game_state_json TEXT DEFAULT '',
	version INTEGER DEFAULT 1,
	created_at INTEGER NOT NULL,
	updated_at INTEGER NOT NULL
);`,
	`CREATE TABLE IF NOT EXISTS "MagicChatMessages" (
	id TEXT PRIMARY KEY,
	lobby_code TEXT NOT NULL,
	user_id TEXT NOT NULL,
	username TEXT NOT NULL,
	avatar_url TEXT DEFAULT '',
	seat_idx INTEGER DEFAULT -1,
	kind TEXT DEFAULT 'chat',
	message TEXT NOT NULL,
	created_at INTEGER NOT NULL
);`,
	`CREATE TABLE IF NOT EXISTS "MagicCardImages" (
	key TEXT PRIMARY KEY,
	image_url TEXT NOT NULL,
	art_crop_url TEXT NOT NULL,
	updated_at INTEGER NOT NULL
);`
];

export function formatSqlValue(value) {
	if (value === null || value === undefined) return 'NULL';
	if (typeof value === 'bigint') return value.toString();
	if (typeof value === 'number') {
		return Number.isFinite(value) ? String(value) : 'NULL';
	}
	if (typeof value === 'boolean') {
		return value ? '1' : '0';
	}
	if (ArrayBuffer.isView(value)) {
		const buf = Buffer.from(value.buffer, value.byteOffset, value.byteLength);
		return `X'${buf.toString('hex')}'`;
	}
	const str = String(value);
	// Escape single quotes as '' (SQLite standard). Keep literal UTF-8 strings intact so both
	// D1 `wrangler d1 execute --file` and `migrate-magic-d1-to-sqlite.mjs` parse pure VALUES literals.
	return `'${str.replace(/'/g, "''")}'`;
}

/**
 * Read a SQLite database and build a D1 SQL script for the 6 Magic tables.
 * Returns `{ sql, counts, insertStatementCount }`.
 */
export function exportSqliteMagicToD1Sql({
	sqliteInputPath,
	maxStatementBytes = DEFAULT_MAX_STATEMENT_BYTES,
	maxRowsPerInsert = DEFAULT_MAX_ROWS_PER_INSERT
}) {
	if (!existsSync(sqliteInputPath)) {
		throw new Error(`Input SQLite file does not exist: ${sqliteInputPath}`);
	}

	const db = new DatabaseSync(sqliteInputPath, { readOnly: true });
	try {
		const existingTables = new Set(
			db
				.prepare("SELECT name FROM sqlite_master WHERE type = 'table'")
				.all()
				.map((r) => String(r.name))
		);

		const lines = [
			'-- Generated by scripts/migrate-magic-sqlite-to-d1.mjs',
			'-- Replaces ONLY the 6 Magic tables in Cloudflare D1 (cosmo_users).',
			...CREATE_SCHEMA_STATEMENTS
		];

		const counts = {};
		let insertStatementCount = 0;

		for (const table of MAGIC_TABLES) {
			lines.push(`DELETE FROM "${table}";`);
			if (!existingTables.has(table)) {
				counts[table] = 0;
				continue;
			}

			const colInfo = db.prepare(`PRAGMA table_info("${table}")`).all();
			const columns = colInfo.map((c) => String(c.name));
			if (columns.length === 0) {
				counts[table] = 0;
				continue;
			}

			const quotedCols = columns.map((c) => `"${c.replace(/"/g, '""')}"`).join(', ');
			const prefix = `INSERT INTO "${table}" (${quotedCols}) VALUES `;

			const rows = db.prepare(`SELECT ${quotedCols} FROM "${table}"`).all();
			counts[table] = rows.length;
			if (rows.length === 0) continue;

			let currentTuples = [];
			let currentBytes = Buffer.byteLength(prefix, 'utf8') + 1; // +1 for ';'

			const flushBatch = () => {
				if (currentTuples.length === 0) return;
				lines.push(`${prefix}${currentTuples.join(',\n')};`);
				insertStatementCount++;
				currentTuples = [];
				currentBytes = Buffer.byteLength(prefix, 'utf8') + 1;
			};

			for (const row of rows) {
				const tuple = `(${columns.map((col) => formatSqlValue(row[col])).join(', ')})`;
				const tupleBytes = Buffer.byteLength(tuple, 'utf8') + 2; // ', ' or ',\n'

				if (
					currentTuples.length > 0 &&
					(currentTuples.length >= maxRowsPerInsert ||
						currentBytes + tupleBytes > maxStatementBytes)
				) {
					flushBatch();
				}

				currentTuples.push(tuple);
				currentBytes += tupleBytes;

				if (Buffer.byteLength(prefix, 'utf8') + tupleBytes > 95_000) {
					console.warn(
						`[migrate-magic-sqlite-to-d1] Warning: single row in ${table} is ~${Math.round(tupleBytes / 1024)} KB (approaching D1 100 KB statement limit).`
					);
				}
			}
			flushBatch();
		}

		return {
			sql: `${lines.join('\n')}\n`,
			counts,
			insertStatementCount
		};
	} finally {
		db.close();
	}
}

function parseCliArgs(argv) {
	const positional = [];
	let maxBytes = DEFAULT_MAX_STATEMENT_BYTES;
	for (const arg of argv) {
		if (arg === '--help' || arg === '-h') {
			return { help: true };
		} else if (arg.startsWith('--max-bytes=')) {
			maxBytes = Number(arg.slice('--max-bytes='.length));
			if (!Number.isFinite(maxBytes) || maxBytes < 1024) {
				throw new Error(`Invalid --max-bytes value: ${arg}`);
			}
		} else if (arg.startsWith('--')) {
			throw new Error(`Unknown flag: ${arg}`);
		} else {
			positional.push(arg);
		}
	}
	return {
		help: false,
		inputPath: positional[0],
		outputPath: positional[1],
		maxBytes
	};
}

const isMain =
	process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (isMain) {
	const parsed = parseCliArgs(process.argv.slice(2));
	if (parsed.help || !parsed.inputPath || !parsed.outputPath) {
		console.error(
			'Usage: node scripts/migrate-magic-sqlite-to-d1.mjs <input.sqlite> <output.sql> [--max-bytes=64000]'
		);
		process.exit(parsed.help ? 0 : 1);
	}

	const result = exportSqliteMagicToD1Sql({
		sqliteInputPath: resolve(parsed.inputPath),
		maxStatementBytes: parsed.maxBytes
	});

	const resolvedOut = resolve(parsed.outputPath);
	mkdirSync(dirname(resolvedOut), { recursive: true });
	writeFileSync(resolvedOut, result.sql, 'utf8');

	console.log(
		`Wrote ${resolvedOut} (${result.insertStatementCount} batched INSERT statement(s)):`
	);
	for (const table of MAGIC_TABLES) {
		console.log(`  ${table.padEnd(20)} ${result.counts[table]} row(s)`);
	}
}
